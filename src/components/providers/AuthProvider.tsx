"use client";

import { SessionProvider } from "next-auth/react";

export function AuthProvider({ children }: { children: React.ReactNode }) {
    return (
        <SessionProvider
            refetchOnWindowFocus={false} // Вимикає запит сесії при кліку чи поверненні фокуса на вікно
            refetchInterval={0}          // Вимикає періодичне фонове оновлення сесії за таймером
        >
            {children}
        </SessionProvider>
    );
}