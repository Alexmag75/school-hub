import { User } from "@/types/user";

/**
 * ==============================================================================
 * SERVICE: Admin User Management Service (`userService`)
 * ==============================================================================
 * @description Клієнтський сервіс для адміністративного модуля.
 *              Забезпечує взаємодію з REST API для управління обліковими записами
 *              користувачів: отримання реєстру, скидання паролів та видалення профілів.
 * ==============================================================================
 */
export const userService = {
    /**
     * @description Отримує повний перелік усіх користувачів системи (учнів, вчителів, адміністраторів).
     *
     * @usecase     Використовується в адміністративній панелі на сторінці управління користувачами (`/admin/users`).
     * @returns     {Promise<User[]>} Масив об'єктів користувачів `User`
     * @throws      {Error} Якщо сервер повернув помилку завантаження
     */
    async getAll(): Promise<User[]> {
        // 1. Відправка GET-запиту до адміністративного маршруту API
        const res = await fetch("/api/admin/users");

        // 2. Перевірка успішності відповіді сервера
        if (!res.ok) throw new Error("Помилка завантаження користувачів");

        // 3. Парсинг та повернення отриманого списку
        return res.json();
    },

    /**
     * @description Скидає поточний пароль користувача та генерує новий тимчасовий пароль.
     *
     * @param {string} userId — Унікальний ідентифікатор користувача в базі даних (Prisma ID)
     * @returns {Promise<string>} Згенерований новий пароль для передачі користувачу
     * @throws {Error} Якщо користувача не знайдено або відсутні права адміністратора
     */
    async resetPassword(userId: string): Promise<string> {
        // 1. POST-запит на спеціалізований ендпоінт скидання пароля
        const res = await fetch(`/api/admin/users/${userId}/reset-password`, {
            method: "POST",
        });

        // 2. Читання відповіді сервера
        const data = await res.json();

        // 3. Обробка помилок із витягуванням точного повідомлення від backend
        if (!res.ok) throw new Error(data.error || "Не вдалося скинути пароль");

        // 4. Повернення нового згенерованого пароля
        return data.newPassword;
    },

    /**
     * @description Безповоротно видаляє обліковий запис користувача з бази даних.
     *
     * @param {string} userId — Унікальний ідентифікатор користувача
     * @throws {Error} Якщо виникла помилка каскадного видалення або недостатньо прав
     */
    async deleteUser(userId: string): Promise<void> {
        // 1. DELETE-запит на видалення запису
        const res = await fetch(`/api/admin/users/${userId}`, {
            method: "DELETE",
        });

        // 2. Перевірка статусу виконання та витягування тексту помилки у разі збою
        if (!res.ok) {
            const data = await res.json();
            throw new Error(data.error || "Не вдалося видалити користувача");
        }
    }
};