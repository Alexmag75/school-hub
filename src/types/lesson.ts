/**
 * ==============================================================================
 * TYPE DEFINITIONS: Lesson Content & Block Editor (`LessonBlock`)
 * ==============================================================================
 * @description Модель даних для блочного конструктора уроків.
 *              Визначає типи контентних блоків (текст, відео, презентації,
 *              інтерактивні вправи) та їхню внутрішню структуру.
 * ==============================================================================
 */

/**
 * @description Допустимі типи блоків у конструкторі матеріалів уроку.
 *
 * @type {"text"}         — Текстовий блок (форматований текст / HTML / Markdown)
 * @type {"image"}        — Зображення (URL або Base64 попередній перегляд)
 * @type {"video"}        — Вбудований відеоплеєр (YouTube, Google Drive)
 * @type {"presentation"} — Інтерактивна презентація (Google Slides, Canva, Prezi)
 * @type {"interactive"}  — Інтерактивна навчальна вправа (Scratch, LearningApps)
 * @type {"embed"}        — Універсальний вбудований iframe-модуль
 */
export type BlockType = "text" | "image" | "video" | "presentation" | "interactive" | "embed";

/**
 * @description Інтерфейс окремого контентного блоку уроку.
 */
export interface LessonBlock {
    /**
     * Унікальний ідентифікатор блоку в межах конструктора (наприклад, "block-1712345678")
     */
    id: string;

    /**
     * Тип блоку, що визначає спосіб його відображення в рендерері
     */
    type: BlockType;

    /**
     * Основний вміст блоку (текст, URL-посилання або скоригований Embed-посилання)
     */
    content: string;

    /**
     * Опціональний підпис до блоку (наприклад, назва відео, примітка до презентації чи джерело)
     */
    caption?: string;
}