/**
 * ==============================================================================
 * TYPE DEFINITIONS: Student Notification System (`StudentNotification`)
 * ==============================================================================
 * @description Визначає структуру типів для системи сповіщень учня.
 *              Використовується для відображення подій у реальному часі: нових завдань,
 *              надуваних дедлайнів, виставлених оцінок та отриманих досягнень.
 * ==============================================================================
 */

/**
 * @description Системні категорії сповіщень для учня.
 *
 * @type {"NEW_ASSIGNMENT"}      — Створено нове домашнє завдання або тест
 * @type {"DEADLINE_WARNING"}   — Попередження про наближення дедлайну виконання
 * @type {"GRADE_RECEIVED"}     — Вчитель перевірив роботу та виставив оцінку
 * @type {"ACHIEVEMENT_UNLOCKED"} — Отримано нову нагороду або бейдж у системі
 */
export type NotificationType =
    | "NEW_ASSIGNMENT"
    | "DEADLINE_WARNING"
    | "GRADE_RECEIVED"
    | "ACHIEVEMENT_UNLOCKED";

/**
 * @description Інтерфейс об'єкта сповіщення учня.
 */
export interface StudentNotification {
    /**
     * Унікальний ідентифікатор сповіщення в базі даних (Prisma ID)
     */
    id: string;

    /**
     * Короткий заголовок сповіщення (наприклад: "Нова оцінка", "Скоро дедлайн")
     */
    title: string;

    /**
     * Детальний текст повідомлення для учня
     */
    message: string;

    /**
     * Категорія сповіщення, що визначає іконку та колірну індикацію в UI
     */
    type: NotificationType;

    /**
     * Дата та час створення сповіщення у форматі ISO 8601
     */
    createdAt: string;

    /**
     * Прапорець прочитання (true — сповіщення прочитане, false — нове)
     */
    isRead: boolean;

    /**
     * Опціональне внутрішнє посилання для швидкого переходу (наприклад: `/student/tasks/123`)
     */
    link?: string;

    /**
     * Опціональна назва предмета, до якого відноситься сповіщення (наприклад: "Фізика", "Інформатика")
     */
    subjectName?: string;
}