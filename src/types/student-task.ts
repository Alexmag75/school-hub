/**
 * ==============================================================================
 * TYPE DEFINITIONS: Student Task & Dashboard Tab Models (`types/student-task.ts`)
 * ==============================================================================
 * @description Визначає структури даних для кабінету учня: типи вкладок фільтрації
 *              та повний інтерфейс картки навчального завдання (уроку, тесту,
 *              контрольної або атестаційної роботи).
 * ==============================================================================
 */

/**
 * @description Вкладки фільтрації завдань у користувацькому інтерфейсі учня.
 *
 * @type {"pending"}            — Активні завдання, що очікують на виконання
 * @type {"completed"}          — Успішно виконані та перевірені роботи
 * @type {"expired"}            — Прострочені завдання, дедлайн виконання яких минув
 * @type {"requires_attention"} — Завдання, що потребують уваги (допрацювання або повторна перевірка)
 */
export type TaskTab = "pending" | "completed" | "expired" | "requires_attention";

/**
 * @description Інтерфейс картки навчального завдання для учня.
 */
export interface StudentTask {
    /** Унікальний ідентифікатор призначення/завдання */
    id: string;

    /** Назва навчальної роботи або теми уроку */
    title: string;

    /** Ідентифікатор вихідного навчального матеріалу (уроку/тесту) */
    materialId: string;

    /** Тип навчального матеріалу (урок, тест, контрольна або атестація) */
    type: "LESSON" | "QUIZ" | "CONTROL_WORK" | "ATTESTATION";

    /** Назва предмета (наприклад: "Фізика", "Інформатика") */
    subjectName: string;

    /** Кінцевий термін здачі у форматі ISO 8601 або null, якщо дедлайн відсутній */
    deadline: string | null;

    /** Обмеження за часом на виконання у хвилинах або null (без таймера) */
    timeLimitMinutes: number | null;

    /** Поточний статус виконання завдання учнем */
    status: "PENDING" | "COMPLETED" | "EXPIRED" | "REQUIRES_ATTENTION";

    /** Набрана кількість тестових балів (якщо роботу перевірено) */
    score?: number;

    /** Максимально можлива кількість балів за завдання */
    maxScore?: number;

    /** Розрахована підсумкова оцінка за 12-бальною шкалою НУШ / МОН України */
    grade12?: number | null;
}