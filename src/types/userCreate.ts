/**
 * @description Інтерфейс новоствореного користувача з тимчасовими доступами.
 *
 * @usecase Використовується при пакетній генерації акаунтів та формуванні
 *          ведомостей для експорту в Excel (`exportUsersToExcel`).
 */
export interface CreatedUser {
    /** Повне ім'я користувача (ПІБ) */
    fullName: string;

    /** Системний логін або електронна пошта */
    email: string;

    /** Згенерований пароль (основне поле) */
    password?: string;

    /** Псевдонім/аліас для пароля (для сумісності з різними генераторами) */
    pass?: string;
}

/**
 * @description Легковаговий інтерфейс навчального класу для селекторів та форм створення.
 */
export interface SchoolClass {
    /** Унікальний ідентифікатор класу */
    id: string;

    /** Назва класу (наприклад: "9-В") */
    name: string;
}

/**
 * @description Легковаговий інтерфейс навчального предмета для випадаючих списків.
 */
export interface Subject {
    /** Унікальний ідентифікатор предмета */
    id: string;

    /** Назва предмета (наприклад: "Фізика", "Інформатика") */
    title: string;
}