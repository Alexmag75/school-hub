/**
 * ==============================================================================
 * UTILITY: 12-Point Grading System Calculator (`calculate12Grade`)
 * ==============================================================================
 * @deprecated  Наразі функція резервна / не використовується в активних модулях.
 *              Збережена як готовий модуль для конвертації тестових балів
 *              у 12-бальну шкалу оцінювання МОН України (Критерії НУШ).
 *
 * @param {number} score — Кількість балів, яку набрав учень
 * @param {number} maxScore — Максимально можлива кількість балів у тесті
 *
 * @returns {number} Підсумкова оцінка за 12-бальною системою (від 1 до 12)
 * ==============================================================================
 */
export function calculate12Grade(score: number, maxScore: number): number {
    // Перевірка некоректних або від'ємних значень
    if (maxScore <= 0 || score <= 0) return 1;

    // Розрахунок відсотка виконання завдання
    const percentage = (score / maxScore) * 100;

    // --------------------------------------------------------------------------
    // ПРОПОРЦІЙНА ШКАЛА ПЕРЕВЕДЕННЯ ВІДСОТКІВ У 12-БАЛЬНУ ОЦІНКУ
    // --------------------------------------------------------------------------

    // Високий рівень (95% - 100%)
    if (percentage >= 95) return 12;
    if (percentage >= 88) return 11;
    if (percentage >= 80) return 10;

    // Достатній рівень (65% - 79%)
    if (percentage >= 73) return 9;
    if (percentage >= 65) return 8;
    if (percentage >= 58) return 7;

    // Середній рівень (40% - 57%)
    if (percentage >= 50) return 6;
    if (percentage >= 40) return 5;
    if (percentage >= 30) return 4;

    // Початковий рівень (менше 40%)
    if (percentage >= 20) return 3;
    if (percentage >= 10) return 2;
    return 1;
}